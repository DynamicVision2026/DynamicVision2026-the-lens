// WO-026 §4: the KDP listing sheet per book (docs/kdp/<book.id>.md), for Brian to copy into KDP. Everything
// comes from book.yaml / the bundle (no new claims); keywords and categories are suggestions Brian picks from.
import { COPY, paragraphs } from './copy';
import type { BookPlan } from './plan';

/** KDP's limit for 内容紹介. */
export const DESCRIPTION_MAX = 4000;

/** Suggested search keywords (7) and Amazon.co.jp categories (2) per Pass. Brian picks. */
const SUGGEST: Record<string, { keywords: string[]; categories: string[] }> = {
  chugaku_juken: {
    keywords: ['中学受験 算数', '算数 問題集', '中学受験 図形', '特殊算', '算数 解き方', '小5 小6 算数', '視点レンズ'],
    categories: ['本 › 参考書・受験書 › 中学受験', '本 › 参考書・受験書 › 小学生 › 算数'],
  },
  koukou_juken: {
    keywords: ['高校受験 数学', '数学 問題集', '座標 図形', '関数と図形', '中学数学 解き方', '中1 中2 中3 数学', '視点レンズ'],
    categories: ['本 › 参考書・受験書 › 高校受験 › 数学', '本 › 参考書・受験書 › 中学生 › 数学'],
  },
  daigaku_juken: {
    keywords: ['大学受験 数学', '共通テスト 数学', '数学 問題集', '二次関数 面積', '図形と方程式', '高校数学 解き方', '視点レンズ'],
    categories: ['本 › 参考書・受験書 › 大学受験 › 数学', '本 › 参考書・受験書 › 高校生 › 数学'],
  },
};

/** 内容紹介: はじめに, the 8 chapters, the honesty line and the QR line, all from book.yaml. */
export function description(plan: BookPlan): string {
  const fm = plan.book.front_matter;
  const chapters = plan.chapters.map((c) => `${COPY.chapter(c.no)}　${c.lensName}`).join('\n');
  return [paragraphs(fm.hajimeni_ja).join('\n'), `【目次】\n${chapters}\n${COPY.review}\n${COPY.answers}`, fm.qr_ja, fm.honesty_ja].join('\n\n');
}

export function listingSheet(plan: BookPlan): string {
  const { book } = plan;
  const s = SUGGEST[plan.passId];
  const desc = description(plan);
  const row = (k: string, v: string) => `| ${k} | ${v} |`;
  return `# KDP listing: ${book.title_ja}

Generated by \`pnpm book ${plan.passId}\` from \`catalog/${plan.passId}/book.yaml\` and the bundle (WO-026 §4). Do not edit by hand.

| 項目 | 内容 |
|---|---|
${[
  row('タイトル', book.title_ja),
  row('サブタイトル', book.subtitle_ja),
  row('シリーズ名', '視点レンズ'),
  row('著者', book.author_ja),
  row('出版社', book.publisher_ja),
  row('言語', '日本語'),
  row('判型', 'B5（182 × 257 mm）'),
  row('本文', '白黒'),
  row('用紙', '白'),
  row('表紙', '光沢'),
  row('ページ数', String(plan.pages.length)),
  row('ISBN', 'KDP 無料 ISBN'),
  row('価格', ''),
].join('\n')}

## 内容紹介（${desc.length} / ${DESCRIPTION_MAX} 字）

\`\`\`text
${desc}
\`\`\`

## キーワード（候補 7）

${s ? s.keywords.map((k, i) => `${i + 1}. ${k}`).join('\n') : '（候補なし）'}

## カテゴリー（候補 2）

${s ? s.categories.map((c, i) => `${i + 1}. ${c}`).join('\n') : '（候補なし）'}
`;
}
